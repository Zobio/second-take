import type { Action } from './types';
import { formatTranscript } from '@/utils/prompt';

/**
 * ここまでの会話をもとに、図をコードで描かせる。
 * 図の種類と形式は送り先のAIに選ばせ、ユーザーは必要なときだけ補足を書く。
 */
export const diagram: Action = {
  id: 'diagram',
  label: '図を作る',
  targetLabel: (t) => `${t.name}で作る`,
  input: { placeholder: '補足（任意）例: 回路図で / 重要な部分を中心に' },

  buildPrompt({ sourceName, messages, note }) {
    return [
      `以下は、ユーザーと別のAIアシスタント（${sourceName}）との会話です。`,
      'この会話の内容を理解するのに役立つ図を1つ作成してください。',
      '',
      '## 進め方',
      '1. 会話の内容に最も合う図の種類を選んでください（フローチャート、シーケンス図、構成図、状態遷移図、ER図、回路図など）。',
      '2. 選んだ種類に合う形式で、図をコードとして描いてください。',
      '   - 処理の流れ・やり取り・構造・状態などの図: Mermaid',
      '   - 回路図: SVG（部品記号と配線のつながりを正確に）',
      '   - それ以外で Mermaid では表しにくい図: SVG',
      '3. 図を画面上に表示できる機能（プレビュー、キャンバス等）があれば、それを使って表示してください。',
      '',
      '## 出力',
      '- 最初に「何を、どの種類の図にしたか」を1〜2文で書いてください。',
      '- 続けて図のコードを、言語名付きのコードブロック（```mermaid や ```svg）で出力してください。',
      '- 会話に出てこない内容を推測で付け足さないでください。不明な部分は図の中で「?」などと明示してください。',
      '',
      note
        ? `## ユーザーからの指示（最優先）\n${note}`
        : '## ユーザーからの指示\n特になし。会話の中心となっている話題を図にしてください。',
      '',
      formatTranscript(sourceName, messages),
    ].join('\n');
  },
};
